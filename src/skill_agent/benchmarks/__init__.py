"""Adapters own task setup and official scoring, not the model loop."""

from typing import Protocol


class BenchmarkAdapter(Protocol):
    snapshot_fingerprint: str
    system_prompt: str
    async def prepare_runtime(self) -> dict: ...
    def tasks(self, split: str, limit: int | None = None) -> list[dict]: ...
    async def open_session(self, task: dict): ...
    def score(self, records: list[dict], output_dir): ...
